package org.SprintForge.modules.workspace.project.entity.enums;

/**
 * Represents the lifecycle status of a Milestone within a Project.
 */
public enum MilestoneStatus {

    /** Milestone is active and in progress. */
    ACTIVE,

    /** Milestone has been completed. */
    COMPLETED,

    /** Milestone has been archived and is no longer actively tracked. */
    ARCHIVED
}
