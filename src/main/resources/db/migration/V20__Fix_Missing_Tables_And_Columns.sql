-- Ensure deleted_at and deleted_by on all SoftDeleteEntity tables
DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN (
        SELECT table_name 
        FROM information_schema.columns 
        WHERE table_schema = 'public' AND column_name = 'is_deleted'
    ) LOOP
        EXECUTE 'ALTER TABLE ' || quote_ident(r.table_name) || ' ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMP WITHOUT TIME ZONE';
        EXECUTE 'ALTER TABLE ' || quote_ident(r.table_name) || ' ADD COLUMN IF NOT EXISTS deleted_by VARCHAR(255)';
    END LOOP;
END $$;

